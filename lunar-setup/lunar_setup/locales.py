def keymap_labels() -> list:
    return [(label, key) for key, label, _, _ in KEYMAPS]


def x11_for(keymap: str) -> tuple:
    for key, _, layout, variant in KEYMAPS:
        if key == keymap:
            return layout, variant
    return "us", ""
